"""
Memory leak detector using statistical trend analysis.

This component consumes historical snapshots generated by the MemoryMonitor
and uses linear regression to detect persistent abnormal memory growth per process.
"""

from typing import List, Dict, Any
import numpy as np
from sklearn.linear_model import LinearRegression


class MemoryLeakDetector:
    """Detects memory leaks based on per-process RSS growth.

    Uses a zero-shot statistical trend approach over a sliding window of recent
    snapshots. It does not perform active management actions.
    """

    def __init__(
        self,
        window_size: int = 10,
        min_growth_bytes_per_step: float = 1024.0,
        min_r2: float = 0.75
    ):
        """
        Args:
            window_size: Number of historical snapshots used to evaluate the trend.
            min_growth_bytes_per_step: Minimum slope (bytes per observation) to flag as a leak.
            min_r2: Minimum R^2 score to ensure the trend is persistently linear.
        """
        if not isinstance(window_size, int) or isinstance(window_size, bool) or window_size < 2:
            raise ValueError(f"window_size must be an integer >= 2, got {window_size!r}")
        
        self.window_size = window_size
        self.min_growth_bytes_per_step = min_growth_bytes_per_step
        self.min_r2 = min_r2

    def detect(self, recent_snapshots: List[Dict[str, Any]]) -> Dict[str, Any]:
        """
        Evaluates a window of recent snapshots for persistent memory growth.

        Args:
            recent_snapshots: A list of dicts from MemoryMonitor.

        Returns:
            Dict containing leak detection results.
        """
        if not isinstance(recent_snapshots, list):
            raise TypeError("recent_snapshots must be a list of dictionaries.")
        
        if len(recent_snapshots) < self.window_size:
            raise ValueError(
                f"Insufficient snapshots for detection. Expected at least {self.window_size}, got {len(recent_snapshots)}"
            )

        # Truncate to the most recent window_size snapshots
        window = recent_snapshots[-self.window_size:]

        # Validate PID uniformity and presence of proc_rss_bytes
        proc_pid = None
        for i, snap in enumerate(window):
            if "proc_pid" not in snap or snap["proc_pid"] is None:
                raise ValueError(f"Snapshot at index {i} is missing a valid 'proc_pid'.")
            if not isinstance(snap["proc_pid"], int):
                raise TypeError(f"Snapshot at index {i} 'proc_pid' must be an integer.")
            
            if proc_pid is None:
                proc_pid = snap["proc_pid"]
            elif snap["proc_pid"] != proc_pid:
                raise ValueError("Mixed PIDs detected in the snapshot window.")

            if "proc_rss_bytes" not in snap or snap["proc_rss_bytes"] is None:
                raise ValueError(f"Snapshot at index {i} is missing 'proc_rss_bytes'.")
            if not isinstance(snap["proc_rss_bytes"], (int, float)):
                raise TypeError(f"Snapshot at index {i} 'proc_rss_bytes' must be numeric.")

        # Extract data for regression
        y = np.array([snap["proc_rss_bytes"] for snap in window])
        X = np.arange(len(window)).reshape(-1, 1)

        # Fit linear regression
        model = LinearRegression()
        model.fit(X, y)

        slope = model.coef_[0]
        # Calculate R^2. If y is perfectly constant, score() handles it natively in scikit-learn
        r2 = model.score(X, y)

        # Determine if leak
        is_leak = bool(slope > self.min_growth_bytes_per_step and r2 > self.min_r2)

        return {
            "is_leak_detected": is_leak,
            "proc_pid": proc_pid,
            "growth_rate_bytes_per_step": float(slope),
            "trend_r2_score": float(r2)
        }

    def evaluate(self, labeled_test_sequences: List[Dict[str, Any]]) -> Dict[str, Any]:
        """
        Evaluates detector accuracy across multiple labeled test sequences.
        """
        if not labeled_test_sequences:
            raise ValueError("Test sequences list is empty.")

        correct = 0
        total = len(labeled_test_sequences)

        for seq in labeled_test_sequences:
            snapshots = seq.get("snapshots", [])
            expected = seq.get("expected_is_leak")

            if expected is None:
                raise ValueError("Test sequence missing 'expected_is_leak' boolean.")

            try:
                result = self.detect(snapshots)
                if result["is_leak_detected"] == expected:
                    correct += 1
            except Exception:
                # Validation errors or exceptions count as a failed prediction
                pass

        accuracy = correct / total if total > 0 else 0.0

        return {
            "total_sequences": total,
            "correct_predictions": correct,
            "accuracy": float(accuracy)
        }

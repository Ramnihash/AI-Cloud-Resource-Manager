"""
Memory-pressure forecaster using scikit-learn Linear Regression.

This component consumes historical snapshots generated by the MemoryMonitor
and uses sliding-window autoregression to forecast the next ram_percent value.
"""

from sklearn.linear_model import LinearRegression
from sklearn.metrics import mean_absolute_error, mean_squared_error


class MemoryPressureForecaster:
    """Forecasts system memory pressure (ram_percent).

    Uses a sliding window approach and a linear regression model to predict
    the next ram_percent from recent snapshots. This is an intelligence/prediction
    layer component and does not perform active management actions.

    Lifecycle::

        forecaster = MemoryPressureForecaster(window_size=5)
        forecaster.train(snapshots)
        forecaster.predict(recent_snapshots)
        forecaster.evaluate(test_snapshots)
    """

    def __init__(self, window_size: int = 5):
        """
        Args:
            window_size: Number of historical snapshots used to predict the next.
        """
        if not isinstance(window_size, int) or isinstance(window_size, bool) or window_size < 1:
            raise ValueError(f"window_size must be an integer >= 1, got {window_size!r}")

        self.window_size = window_size
        self._trained = False
        self.model = None

    def _extract_ram_percent(self, snapshots: list) -> list:
        """Helper to extract and validate 'ram_percent' from a list of snapshots."""
        if not isinstance(snapshots, list):
            raise TypeError(f"snapshots must be a list, got {type(snapshots).__name__}")

        values = []
        for idx, s in enumerate(snapshots):
            if not isinstance(s, dict):
                raise TypeError(f"snapshot at index {idx} must be a dict, got {type(s).__name__}")
            if "ram_percent" not in s:
                raise ValueError(f"snapshot at index {idx} missing 'ram_percent' key")

            val = s["ram_percent"]
            if not isinstance(val, (int, float)) or isinstance(val, bool):
                raise TypeError(f"'ram_percent' at index {idx} must be numeric, got {type(val).__name__}")
            if not (0.0 <= val <= 100.0):
                raise ValueError(f"'ram_percent' at index {idx} must be in [0, 100], got {val}")

            values.append(float(val))
        return values

    def train(self, snapshots: list) -> dict:
        """Train the forecaster using sliding-window autoregression.

        Args:
            snapshots: List of memory snapshot dictionaries.

        Returns:
            Dictionary with training summary metrics.
        """
        values = self._extract_ram_percent(snapshots)

        if len(values) < self.window_size + 1:
            raise ValueError(
                f"Need at least window_size + 1 ({self.window_size + 1}) snapshots "
                f"for training, got {len(values)}"
            )

        X = []
        y = []
        for i in range(len(values) - self.window_size):
            X.append(values[i : i + self.window_size])
            y.append(values[i + self.window_size])

        self.model = LinearRegression()
        self.model.fit(X, y)
        self._trained = True

        return {
            "window_size": self.window_size,
            "training_samples": len(X),
        }

    def predict(self, recent_snapshots: list) -> dict:
        """Predict the next memory utilization value.

        Args:
            recent_snapshots: Exactly `window_size` recent snapshots.

        Returns:
            Dictionary containing 'predicted_ram_percent'.
        """
        self._require_trained("predict")
        values = self._extract_ram_percent(recent_snapshots)

        if len(values) != self.window_size:
            raise ValueError(
                f"predict requires exactly window_size ({self.window_size}) "
                f"snapshots, got {len(values)}"
            )

        pred_val = self.model.predict([values])[0]

        pred_val = max(0.0, min(100.0, float(pred_val)))

        return {
            "predicted_ram_percent": pred_val
        }

    def evaluate(self, test_snapshots: list) -> dict:
        """Evaluate the forecaster against a test sequence of snapshots.

        Args:
            test_snapshots: List of memory snapshot dictionaries.

        Returns:
            Dictionary with MAE, MSE, and total_predictions.
        """
        self._require_trained("evaluate")
        values = self._extract_ram_percent(test_snapshots)

        if len(values) < self.window_size + 1:
            raise ValueError(
                f"Need at least window_size + 1 ({self.window_size + 1}) test snapshots, "
                f"got {len(values)}"
            )

        X_test = []
        y_true = []
        for i in range(len(values) - self.window_size):
            X_test.append(values[i : i + self.window_size])
            y_true.append(values[i + self.window_size])

        preds_raw = self.model.predict(X_test)

        preds = [max(0.0, min(100.0, float(p))) for p in preds_raw]

        mae = mean_absolute_error(y_true, preds)
        mse = mean_squared_error(y_true, preds)

        return {
            "MAE": mae,
            "MSE": mse,
            "total_predictions": len(y_true)
        }

    def _require_trained(self, method_name: str) -> None:
        """Raise RuntimeError if the model is not trained."""
        if not self._trained:
            raise RuntimeError(
                f"MemoryPressureForecaster.{method_name}() called before train()."
            )
